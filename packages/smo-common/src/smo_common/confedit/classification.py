#: catch-alls so every file has a classification (first match wins above).
_FALLBACKS = [
    FileClass("**/*.yaml", "simulation", "Unclassified YAML config", True,
              ALL, "Not in the classification table — treated as "
              "restart-everything out of caution."),
    FileClass("**/*", "junk", "Unclassified file", False, (),
              "Not a config file the editor knows; not editable."),
]


def classify(relpath: str) -> FileClass:
    """Classification for a configs-relative posix path. Always returns."""
    rp = relpath.replace("\\", "/").lstrip("/")
    for rule in _TABLE + _FALLBACKS:
        if fnmatch.fnmatch(rp, rule.pattern):
            return rule
    return _FALLBACKS[-1]  # pragma: no cover — '**/*' always matches


def classification_table() -> list[dict]:
    """The full rule table, JSON-shaped (for the API/UI and for tests)."""
    return [
        {
            "pattern": r.pattern,
            "group": r.group,
            "label": r.label,
            "editable": r.editable,
            "restart_scope": list(r.restart_scope),
            "note": r.note,
            "interface_defining": r.interface_defining,
        }
        for r in _TABLE
    ]
