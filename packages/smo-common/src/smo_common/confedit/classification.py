"""Editability classification of every mission config file — encoded as data.

The table transcribes brief 06 §B's classification: what each file is, who
may edit it, which services must restart for a change to take effect, and
the files that must never be edited (dead config that no code reads, and
generated artefacts that regeneration would overwrite).

Rules are matched in order, first match wins; ``classify()`` therefore
handles files that do not exist yet (e.g. a new ``subsystems/<x>.yaml``)
through the directory patterns, so adding a config file never leaves it
unclassified.
"""
from __future__ import annotations

import fnmatch
from dataclasses import dataclass, field

__all__ = ["FileClass", "classify", "classification_table", "GROUP_ORDER"]


@dataclass(frozen=True)
class FileClass:
    #: matching pattern (fnmatch over the configs-relative posix path)
    pattern: str
    #: group key (see GROUP_ORDER)
    group: str
    #: human label shown in the UI tree
    label: str
    #: False → server-side rejected on any write attempt
    editable: bool
    #: services that must restart for an edit to take effect
    restart_scope: tuple[str, ...] = ()
    #: why it is not editable / why it is dangerous
    note: str = ""
    #: interface-defining files get an extra confirmation gate in the UI
    interface_defining: bool = False


